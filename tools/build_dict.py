def key(word):
    return word.lower().translate(ACCENTS)


# ---------------------------------------------------------------- downloads

def fetch(url, dest):
    if dest.exists():
        return dest
    print(f"downloading {url}", flush=True)
    CACHE.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url) as r, open(tmp, "wb") as f:
        while True:
            chunk = r.read(1 << 20)
            if not chunk:
                break
            f.write(chunk)
    tmp.rename(dest)
    return dest


def ngram_counts():
    dest = CACHE / "ngram_spa_1980.tsv"
    if not dest.exists():
        ok = re.compile(r"^[a-záéíóúüñ]{3,8}$", re.I)
        low, cap = defaultdict(int), defaultdict(int)
        for i in range(3):
            print(f"streaming Ngram file {i + 1}/3 (large)", flush=True)
            with urllib.request.urlopen(NGRAM_URL.format(i)) as resp:
                for raw in gzip.GzipFile(fileobj=resp):
                    line = raw.decode("utf-8", "replace")
                    tab = line.find("\t")
                    tok = line[:tab]
                    if not ok.match(tok):
                        continue
                    total = sum(int(r.split(",")[1]) for r in line[tab + 1:].split("\t") if int(r[:4]) >= 1980)
                    if total:
                        (low if tok == tok.lower() else cap)[tok.lower()] += total
        CACHE.mkdir(parents=True, exist_ok=True)
        with open(dest, "w", encoding="utf-8") as f:
            for w in sorted(set(low) | set(cap)):
                f.write(f"{w}\t{low.get(w, 0)}\t{cap.get(w, 0)}\n")
    low, cap = {}, {}
    with open(dest, encoding="utf-8") as f:
        for line in f:
            w, l, c = line.rstrip("\n").split("\t")
            low[w], cap[w] = int(l), int(c)
    return low, cap


def tatoeba_counts():
    path = fetch(TATOEBA_URL, CACHE / "spa_sentences.tsv.bz2")
    counts = defaultdict(int)
    tok = re.compile(r"[a-záéíóúüñ]+")
    with bz2.open(path, "rt", encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            for w in tok.findall(parts[2].lower()):
                counts[w] += 1
    return counts


# ---------------------------------------------------------------- hunspell expansion

class Affixes:
    """Minimal hunspell .aff reader for the RLA-ES files: FLAG UTF-8, PFX/SFX, cross product,
    continuation classes on affixes. No compounding (the files use none)."""

    def __init__(self, path):
        self.sfx, self.pfx = {}, {}
        lines = path.read_text(encoding="utf-8").splitlines()
        i = 0
        while i < len(lines):
            p = lines[i].split()
            if len(p) == 4 and p[0] in ("SFX", "PFX") and p[2] in ("Y", "N") and p[3].isdigit():
                kind, flag, cross, n = p[0], p[1], p[2] == "Y", int(p[3])
                rules = []
                for j in range(1, n + 1):
                    r = lines[i + j].split()
                    strip = "" if r[2] == "0" else r[2]
                    add, _, cont = r[3].partition("/")
                    add = "" if add == "0" else add
                    cond = r[4] if len(r) > 4 else "."
                    rx = re.compile((cond + "$") if kind == "SFX" else ("^" + cond))
                    rules.append((strip, add, cont, rx))
                (self.sfx if kind == "SFX" else self.pfx)[flag] = (cross, rules)
                i += n + 1
            else:
                i += 1

    def _sfx(self, word, flag):
        cross, rules = self.sfx[flag]
        for strip, add, cont, rx in rules:
            if word.endswith(strip) and rx.search(word):
                yield word[:len(word) - len(strip)] + add, cont, cross

    def _pfx(self, word, flag):
        cross, rules = self.pfx[flag]
        for strip, add, cont, rx in rules:
            if word.startswith(strip) and rx.search(word):
                yield add + word[len(strip):], cross

    def expand(self, word, flags):
        out = {word}
        crossable = [word]
        for f in flags:
            if f in self.sfx:
                for form, cont, cross in self._sfx(word, f):
                    out.add(form)
                    if cross:
                        crossable.append(form)
                    for c in cont:
                        if c in self.sfx:
                            for form2, _, _ in self._sfx(form, c):
                                out.add(form2)
                        elif c in self.pfx:
                            for form2, _ in self._pfx(form, c):
                                out.add(form2)
        for f in flags:
            if f in self.pfx:
                cross_p = self.pfx[f][0]
                for base in (crossable if cross_p else [word]):
                    for form, _ in self._pfx(base, f):
                        out.add(form)
        return out


def is_verb(word, expanded):
    """Infinitive whose expansion has the 1st person plural present (cantamos, comemos, pedimos, reímos)."""
    if word.endswith(("ar", "er", "ir")):
        return word[:-1] + "mos" in expanded
    if word.endswith("ír"):
        return word[:-2] + "ímos" in expanded
    return False


def has_plural(word, expanded):
    """Noun/adjective lemma: some expanded form is its plural (casa/casas, canción/canciones, lápiz/lápices)."""
    k = key(word)
    for f in expanded:
        if f != word and f.endswith("s") and 1 <= len(f) - len(word) <= 2 and key(f).startswith(k[:-1]):
            return True
    return False


def hunspell_words():
    """Returns (forms, nouns, verbs, verbforms, nounforms): every 3-8 letter form, noun/adjective lemmas with a
    plural, verb infinitives, every form generated from a verb (conjugations, clitics) and every form generated
    from a noun/adjective (plurals, feminines)."""
    forms, nouns, verbs, verbforms, nounforms = set(), set(), set(), set(), set()
    per_locale = {}
    for loc in LOCALES:
        loc_forms = per_locale.setdefault(loc, set())
        aff = Affixes(fetch(DICT_URL.format(loc + ".aff"), CACHE / (loc + ".aff")))
        dic = fetch(DICT_URL.format(loc + ".dic"), CACHE / (loc + ".dic"))
        lines = dic.read_text(encoding="utf-8").splitlines()[1:]
        for line in lines:
            entry = line.split()[0] if line.strip() else ""
            word, _, flags = entry.partition("/")
            if not word or not word[0].islower():
                continue  # proper nouns, acronyms
            if not WORD_RE.match(word):
                continue
            expanded = aff.expand(word, flags)
            verb = is_verb(word, expanded)
            if verb:
                verbs.add(word)
                verbforms.update(expanded)
            elif has_plural(word, expanded):
                nouns.add(word)
                nounforms.update(expanded)
            for form in expanded:
                if MIN_LEN <= len(form) <= MAX_LEN and WORD_RE.match(form):
                    forms.add(form)
                    loc_forms.add(form)
    for name in ("README_hunspell_es.txt", "LICENSE.md"):
        fetch(DICT_URL.format(name), CACHE / name)
    # verb forms shared by Spain and Mexico: drops vosotros (habláis, elegid) and voseo (tenés, vení) from levels
    core_verbforms = verbforms & per_locale.get("es_ES", forms) & per_locale.get("es_MX", forms)
    return forms, nouns - verbs, verbs, verbforms, nounforms - verbs, core_verbforms


CLITICS = ("los", "las", "les", "nos", "lo", "la", "le", "me", "te", "se", "os")


def is_awkward_verbform(w, verbs, formkeys, nounforms, verbforms, core_verbforms):
    """Forms we accept as bonus words but never place in a crossword or use as answers:
    verb + enclitic pronoun (déjalos, dádmelo, hacenos), vosotros/voseo forms (habláis, tenés, cerrás, hablá)
    and vosotros imperatives (elegid, recordad). Nouns and adjectives are never awkward (tomate, parte)."""
    if w in nounforms:
        return False
    if w in verbforms and w not in core_verbforms:
        return True
    for c in CLITICS:
        if w.endswith(c) and len(w) - len(c) >= 3 and key(w[:-len(c)]) in formkeys:
            return True
    if w.endswith(("ad", "ed", "id")) and (w[:-1] + "r") in verbs:
        return True
    return False


# ---------------------------------------------------------------- blocklist

def load_blocklist():
    lists = {"hard": [], "soft": []}
    cur = None
    for line in (ROOT / "tools" / "blocklist.txt").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line in ("[hard]", "[soft]"):
            cur = line[1:-1]
            continue
        lists[cur].append(re.compile("^(?:" + line + ")$"))
    return lists


def matches(rxs, k):
    return any(r.match(k) for r in rxs)


# ---------------------------------------------------------------- main

def front_code(sorted_words):
    out, prev = [], ""
    for w in sorted_words:
        n = 0
        while n < min(len(prev), len(w), 9) and prev[n] == w[n]:
            n += 1
        out.append(w if n == 0 else f"{n}{w[n:]}")
        prev = w
    return " ".join(out)


def zipf(count, total):
    return math.log10(count * 1e9 / total + 1) if count else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stats", action="store_true")
    args = ap.parse_args()

    forms, nouns, verbs, verbforms, nounforms, core_verbforms = hunspell_words()
    print(f"hunspell: {len(forms)} forms of {MIN_LEN}-{MAX_LEN} letters, {len(nouns)} noun/adjective lemmas, {len(verbs)} verbs")
    formkeys = {key(f) for f in forms}
    ng_low, ng_cap = ngram_counts()
    tat = tatoeba_counts()
    ng_total = sum(ng_low.values()) + sum(ng_cap.values())
    tat_total = sum(tat.values())
    block = load_blocklist()

    # score every hunspell form; 60 % conversational (Tatoeba), 40 % books (Ngram)
    by_key = {}
    dropped = defaultdict(int)
    for w in forms:
        k = key(w)
        if matches(block["hard"], k):
            dropped["hard_block"] += 1
            continue
        if not (set(w) & VOWELS) or ROMAN_RE.match(k) or k in ABBREVIATIONS:
            dropped["no_vowel_or_roman"] += 1
            continue
        low = ng_low.get(w, 0)
        t = tat.get(w, 0)
        if low < 50 and t == 0:
            dropped["no_frequency_evidence"] += 1
            continue
        score = 0.6 * zipf(t, tat_total) + 0.4 * zipf(low, ng_total)
        cur = by_key.get(k)
        if cur is None:
            aw = is_awkward_verbform(w, verbs, formkeys, nounforms, verbforms, core_verbforms)
            by_key[k] = {"form": w, "form_awkward": aw, "score": score, "best": score, "lemma": w in nouns, "noun_form": w if w in nouns else None, "conj": w in verbforms and w not in nounforms and w not in verbs, "awkward": aw, "low": low, "cap": ng_cap.get(w, 0), "tat": t}
        else:
            cur["score"] = max(cur["score"], score)
            cur["low"] += low
            cur["cap"] += ng_cap.get(w, 0)
            cur["tat"] += t
            cur["lemma"] = cur["lemma"] or (w in nouns)
            if w in nouns:
                cur["noun_form"] = w
            cur["conj"] = cur["conj"] and w in verbforms and w not in nounforms and w not in verbs
            aw = is_awkward_verbform(w, verbs, formkeys, nounforms, verbforms, core_verbforms)
            # display form: prefer a pan-Hispanic form (probas over probás), then the most frequent
            if (cur["form_awkward"], -cur["best"]) > (aw, -score):
                cur["form"], cur["best"], cur["form_awkward"] = w, score, aw
            cur["awkward"] = cur["awkward"] and aw

    common_pool = []
    for k, d in by_key.items():
        if matches(block["soft"], k):
            continue
        if d["cap"] > 4 * max(d["low"], 1):
            continue  # mostly written capitalised in books: a name or place ("lima", "paris")
        if d["tat"] < 2:
            continue  # level words must appear in everyday sentences
        if d["awkward"]:
            continue  # déjalos, casaros, elegid: valid bonus words, odd crossword answers
        common_pool.append((d["score"], k))
    common_pool.sort(key=lambda x: (-x[0], x[1]))
    # conjugated verb forms only while they are really frequent (tiene, dijo, vamos); vosotros/voseo never
    common_keys, n_conj = [], 0
    for _, k in common_pool:
        d = by_key[k]
        if d["conj"]:
            if n_conj >= MAX_CONJ or d["form"].endswith(("áis", "éis", "ís", "ás", "és")) and d["tat"] < 50:
                continue
            n_conj += 1
        common_keys.append(k)
        if len(common_keys) == COMMON_SIZE:
            break
    common_set = set(common_keys)
    bonus_keys = sorted(k for k in by_key if k not in common_set)

    # daily: 5-letter noun/adjective lemmas (have a plural; not verbs, so no conjugations or infinitives)
    daily_pool = [k for k in common_keys if len(k) == 5 and by_key[k]["lemma"] and by_key[k]["tat"] >= 5]
    if len(daily_pool) < DAILY_DAYS:
        sys.exit(f"only {len(daily_pool)} daily candidates")
    daily_pool = daily_pool[:int(DAILY_DAYS * 1.25)]
    rng = random.Random(DAILY_SEED)
    rng.shuffle(daily_pool)
    daily = [by_key[k]["noun_form"] or by_key[k]["form"] for k in daily_pool[:DAILY_DAYS]]

    OUT.mkdir(parents=True, exist_ok=True)
    common_str = " ".join(by_key[k]["form"] for k in common_keys)
    bonus_str = front_code(bonus_keys)
    (OUT / "words.js").write_text(
        MPL_HEADER + "window.PALABRAS_WORDS = " + json.dumps({"v": 1, "common": common_str, "bonus": bonus_str},
                                                             ensure_ascii=False) + ";\n", encoding="utf-8", newline="\n")
    (OUT / "daily.js").write_text(
        MPL_HEADER + "window.PALABRAS_DAILY = " + json.dumps(daily, ensure_ascii=False) + ";\n",
        encoding="utf-8", newline="\n")

    stats = {
        "hunspell_forms_3_8": len(forms),
        "accepted_keys": len(by_key),
        "common": len(common_keys),
        "bonus_only": len(bonus_keys),
        "daily": len(daily),
        "dropped": dict(dropped),
        "by_length_common": {n: sum(1 for k in common_keys if len(k) == n) for n in range(MIN_LEN, MAX_LEN + 1)},
        "words_js_kb": round((OUT / "words.js").stat().st_size / 1024, 1),
        "daily_js_kb": round((OUT / "daily.js").stat().st_size / 1024, 1),
    }
    (ROOT / "tools" / "dict_stats.json").write_text(json.dumps(stats, indent=1, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(stats, indent=1, ensure_ascii=False))
    if args.stats:
        print("top 60:", " ".join(by_key[k]["form"] for k in common_keys[:60]))
        print("rank 5000-5040:", " ".join(by_key[k]["form"] for k in common_keys[5000:5040]))
        print("rank 19960-20000:", " ".join(by_key[k]["form"] for k in common_keys[19960:20000]))
        print("daily sample:", daily[:40])
        print("bonus sample:", bonus_keys[::5000])


if __name__ == "__main__":
    main()
